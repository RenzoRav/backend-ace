CREATE TABLE brand (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE category (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE customer (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  name VARCHAR(255) NOT NULL,
  phone VARCHAR(255) NOT NULL UNIQUE,
  birthday DATE
);

CREATE TABLE customer_account (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  customer_id BIGINT NOT NULL UNIQUE REFERENCES customer(id),
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  credential_version BIGINT NOT NULL
);

CREATE TABLE manager (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  credential_version BIGINT NOT NULL,
  active BOOLEAN NOT NULL
);

CREATE TABLE product (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  brand_id BIGINT NOT NULL REFERENCES brand(id),
  category_id BIGINT NOT NULL REFERENCES category(id),
  name VARCHAR(255) NOT NULL,
  description VARCHAR(4000),
  image_url VARCHAR(4000),
  price NUMERIC(14,2) NOT NULL,
  cost NUMERIC(14,2) NOT NULL,
  stock INTEGER NOT NULL,
  minimum_stock INTEGER NOT NULL,
  active BOOLEAN NOT NULL,
  CHECK(price >= 0 AND cost >= 0 AND stock >= 0 AND minimum_stock >= 0)
);

CREATE TABLE coupon (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  code VARCHAR(255) NOT NULL UNIQUE,
  type VARCHAR(255) NOT NULL,
  value NUMERIC(14,2) NOT NULL,
  valid_from DATE NOT NULL,
  valid_until DATE NOT NULL,
  usage_limit INTEGER,
  CHECK(type IN ('FIXED','PERCENT') AND value >= 0 AND (type <> 'PERCENT' OR value <= 100) AND valid_until >= valid_from AND (usage_limit IS NULL OR usage_limit > 0))
);

CREATE TABLE promotion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  name VARCHAR(255) NOT NULL,
  percent NUMERIC(14,2) NOT NULL,
  valid_from DATE NOT NULL,
  valid_until DATE NOT NULL,
  CHECK(percent BETWEEN 0 AND 100 AND valid_until >= valid_from)
);

CREATE TABLE product_promotion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  product_id BIGINT NOT NULL REFERENCES product(id),
  promotion_id BIGINT NOT NULL REFERENCES promotion(id),
  UNIQUE(product_id,promotion_id)
);

CREATE TABLE interest_rate (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  installment_count INTEGER NOT NULL UNIQUE,
  percent NUMERIC(14,2) NOT NULL,
  CHECK(installment_count BETWEEN 1 AND 12 AND percent >= 0)
);

CREATE TABLE purchase_order (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  customer_id BIGINT NOT NULL REFERENCES customer(id),
  coupon_id BIGINT REFERENCES coupon(id),
  interest_rate_id BIGINT REFERENCES interest_rate(id),
  status VARCHAR(255) NOT NULL,
  payment_status VARCHAR(255) NOT NULL,
  payment_method VARCHAR(255) NOT NULL,
  stock_effect VARCHAR(255) NOT NULL,
  origin VARCHAR(255) NOT NULL,
  subtotal NUMERIC(14,2) NOT NULL,
  discount NUMERIC(14,2) NOT NULL,
  shipping NUMERIC(14,2) NOT NULL,
  interest NUMERIC(14,2) NOT NULL,
  total NUMERIC(14,2) NOT NULL,
  installment_count INTEGER NOT NULL,
  delivery BOOLEAN NOT NULL,
  address_snapshot VARCHAR(4000),
  idempotency_key VARCHAR(255) UNIQUE,
  request_hash VARCHAR(255),
  customer_name VARCHAR(255) NOT NULL,
  customer_phone VARCHAR(255) NOT NULL,
  CHECK(total >= 0 AND installment_count BETWEEN 1 AND 12 AND status IN ('NEW','CONFIRMED','PREPARING','FINISHED','CANCELLED'))
);

CREATE TABLE order_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  order_id BIGINT NOT NULL REFERENCES purchase_order(id),
  product_id BIGINT NOT NULL REFERENCES product(id),
  quantity INTEGER NOT NULL,
  unit_price NUMERIC(14,2) NOT NULL,
  unit_cost NUMERIC(14,2) NOT NULL,
  product_name VARCHAR(255) NOT NULL,
  brand_name VARCHAR(255) NOT NULL,
  category_name VARCHAR(255) NOT NULL,
  CHECK(quantity > 0 AND unit_price >= 0 AND unit_cost >= 0)
);

CREATE TABLE installment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  order_id BIGINT NOT NULL REFERENCES purchase_order(id),
  number INTEGER NOT NULL,
  amount NUMERIC(14,2) NOT NULL,
  due_date DATE NOT NULL,
  status VARCHAR(255) NOT NULL,
  paid_at TIMESTAMPTZ,
  UNIQUE(order_id,number),
  CHECK(amount > 0 AND number > 0 AND status IN ('PENDING','PAID','CANCELLED'))
);

CREATE TABLE billing_record (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  installment_id BIGINT NOT NULL REFERENCES installment(id),
  message VARCHAR(4000) NOT NULL,
  declared_sent_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE inventory_movement (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  product_id BIGINT NOT NULL REFERENCES product(id),
  order_id BIGINT REFERENCES purchase_order(id),
  type VARCHAR(255) NOT NULL,
  quantity INTEGER NOT NULL,
  description VARCHAR(4000)
);

CREATE TABLE financial_movement (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  order_id BIGINT REFERENCES purchase_order(id),
  installment_id BIGINT REFERENCES installment(id),
  type VARCHAR(255) NOT NULL,
  description VARCHAR(255) NOT NULL,
  amount NUMERIC(14,2) NOT NULL,
  CHECK(amount > 0 AND type IN ('IN','OUT'))
);

CREATE TABLE birthday_benefit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  customer_id BIGINT NOT NULL REFERENCES customer(id),
  coupon_id BIGINT REFERENCES coupon(id),
  year INTEGER NOT NULL,
  granted_at TIMESTAMPTZ NOT NULL,
  UNIQUE(customer_id,year)
);

CREATE TABLE gift (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  customer_id BIGINT NOT NULL REFERENCES customer(id),
  description VARCHAR(255) NOT NULL,
  date DATE NOT NULL
);

CREATE TABLE audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  manager_id BIGINT NOT NULL REFERENCES manager(id),
  action VARCHAR(255) NOT NULL,
  entity VARCHAR(255) NOT NULL,
  entity_id VARCHAR(255) NOT NULL
);

CREATE TABLE status_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  order_id BIGINT NOT NULL REFERENCES purchase_order(id),
  manager_id BIGINT REFERENCES manager(id),
  previous_status VARCHAR(255),
  next_status VARCHAR(255) NOT NULL
);

CREATE TABLE customer_address (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  customer_id BIGINT NOT NULL REFERENCES customer(id),
  label VARCHAR(255) NOT NULL,
  postal_code VARCHAR(255) NOT NULL,
  street VARCHAR(255) NOT NULL,
  number VARCHAR(255) NOT NULL,
  complement VARCHAR(255),
  district VARCHAR(255) NOT NULL,
  city VARCHAR(255) NOT NULL,
  state VARCHAR(255) NOT NULL
);

CREATE TABLE support_ticket (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  customer_id BIGINT NOT NULL REFERENCES customer(id),
  order_id BIGINT REFERENCES purchase_order(id),
  subject VARCHAR(255) NOT NULL,
  message VARCHAR(4000) NOT NULL,
  status VARCHAR(255) NOT NULL,
  reply VARCHAR(4000)
);

CREATE TABLE refresh_session (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  role VARCHAR(255) NOT NULL,
  account_id BIGINT NOT NULL,
  token_hash VARCHAR(255) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  revoked BOOLEAN NOT NULL
);

CREATE INDEX idx_order_customer ON purchase_order(customer_id);
CREATE INDEX idx_order_item_order ON order_item(order_id);
CREATE INDEX idx_inventory_product ON inventory_movement(product_id);
CREATE INDEX idx_financial_order ON financial_movement(order_id);
CREATE INDEX idx_installment_due ON installment(status,due_date);
